/**
 * The modules of `flags:<source>`, from the flags files. For each source of
 * the flags files, it writes one module into `.flags/<source>.ts`, which
 * re-exports the flags of the source from all files. A framework plugin
 * points the alias `flags:<source>` to the module. TypeScript finds the
 * types in `flags/generated.d.ts`.
 *
 * The flags files are the only declarations of the flags: nothing here uses
 * the network or the flag management system.
 */
import { randomUUID } from 'node:crypto';
import {
  mkdir,
  readdir,
  readFile,
  rename,
  rm,
  stat,
  writeFile,
} from 'node:fs/promises';
import path from 'node:path';
import { findFlagsFiles } from './find-flags-modules';
import { jsDocOf } from './flags-file/compile';
import {
  watchFlagsFileDeclarations,
  writeFlagsFileDeclarations,
} from './flags-file/declarations';
import { parseFlagsFile } from './flags-file/document';
import { GENERATED_DIRECTORY } from './generated-directory';

export { GENERATED_DIRECTORY };

/**
 * The aliases of the generated modules, e.g.
 * `{ 'flags:site': './.flags/site.ts' }`. Relative to the directory of the
 * application.
 */
export type FlagsAliases = Record<string, string>;

/**
 * Checks the name of a source. The name is a part of the module specifier
 * `flags:<source>` and of the file `.flags/<source>.ts`.
 */
function assertSourceName(name: string): void {
  if (!/^[a-z][a-z0-9_-]*$/i.test(name)) {
    throw new Error(`flags: Invalid name of a source: ${JSON.stringify(name)}`);
  }
}

async function isFile(file: string): Promise<boolean> {
  const info = await stat(file).catch(() => null);
  return info?.isFile() ?? false;
}

async function writeIfChanged(
  directory: string,
  filename: string,
  content: string,
): Promise<void> {
  const target = path.join(directory, filename);
  const previous = await readFile(target, 'utf8').catch(() => null);
  if (previous === content) {
    return;
  }
  // A file watcher must never see a module which is only partly written
  const temporary = `${target}.${randomUUID()}.tmp`;
  try {
    await writeFile(temporary, content);
    await rename(temporary, target);
  } finally {
    await rm(temporary, { force: true });
  }
}

/**
 * The name of the declarations of the modules `flags:<source>`, in the
 * folder `flags` of the application.
 */
export const GENERATED_DECLARATIONS = 'generated.d.ts';

/**
 * Finds the folder `flags` with the sources: in the directory of the
 * application, or in its `src` directory, as for `flags/config.ts`. The SDK
 * never creates this folder, so it is where the application put it.
 */
export async function findFlagsDirectory(
  directory: string,
): Promise<string | undefined> {
  for (const base of [directory, path.join(directory, 'src')]) {
    const flags = path.join(base, 'flags');
    const info = await stat(path.join(flags, 'sources')).catch(() => null);
    if (info?.isDirectory()) {
      return flags;
    }
  }
  return undefined;
}

/**
 * Finds `flags/generated.d.ts`, the types of `flags:<source>`, which the
 * code generation wrote: in the directory of the application, or in its
 * `src` directory. Also for the default source `self` without a folder
 * `flags/sources`.
 */
export async function findGeneratedDeclarations(
  directory: string,
): Promise<string | undefined> {
  for (const base of [directory, path.join(directory, 'src')]) {
    const file = path.join(base, 'flags', GENERATED_DECLARATIONS);
    if (await isFile(file)) {
      return file;
    }
  }
  return undefined;
}

/**
 * Where the folder `flags` goes for the default source, if the application
 * has none: into `src`, if the application has `src`, as for SvelteKit.
 */
async function defaultFlagsDirectory(directory: string): Promise<string> {
  // A folder flags which exists, e.g. with flags/config.ts, comes first
  for (const base of [directory, path.join(directory, 'src')]) {
    const flags = path.join(base, 'flags');
    const info = await stat(flags).catch(() => null);
    if (info?.isDirectory()) {
      return flags;
    }
  }
  const src = path.join(directory, 'src');
  const info = await stat(src).catch(() => null);
  return path.join(info?.isDirectory() ? src : directory, 'flags');
}

/**
 * The first line of `generated.d.ts`. Only a file with this line is removed
 * from a place where the declarations are no longer written.
 */
const DECLARATIONS_HEADER = '// Generated by the Flags SDK';

/**
 * Removes `generated.d.ts` from the other possible folder `flags`, e.g. from
 * `src/flags` after `flags/sources` was created in the root. Otherwise two
 * files declare the modules `flags:<source>`. A file which the SDK did not
 * write stays.
 */
async function removeOtherDeclarations(
  directory: string,
  flagsDirectory: string,
): Promise<void> {
  for (const base of [directory, path.join(directory, 'src')]) {
    const flags = path.join(base, 'flags');
    if (path.resolve(flags) === path.resolve(flagsDirectory)) {
      continue;
    }
    const file = path.join(flags, GENERATED_DECLARATIONS);
    const content = await readFile(file, 'utf8').catch(() => undefined);
    if (content?.startsWith(DECLARATIONS_HEADER)) {
      await rm(file, { force: true });
    }
  }
}

function importPath(fromDirectory: string, file: string): string {
  const relative = path.relative(fromDirectory, file).split(path.sep).join('/');
  return relative.startsWith('.') ? relative : `./${relative}`;
}

interface SourceFlag {
  readonly key: string;
  /** The name of the flag, and of its export */
  readonly name: string;
  readonly file: string;
  readonly doc: readonly string[];
}

export interface FlagsFileSourcesResult {
  /** The aliases of the modules of the sources, as for `generateFlags` */
  readonly aliases: FlagsAliases;
  /**
   * Flags of two files with the same source and the same key or the same
   * name. The second one is not in `flags:<source>`.
   */
  readonly conflicts: readonly string[];
}

/**
 * Writes the module of each source of the flags files, so that an
 * application can import a flag from its source, e.g.
 * `import { summerSale } from 'flags:self'`, as well as from its file. The
 * module of a source re-exports the flags of the source from all flags
 * files, with their names. The source of a flag is its field `source`, or
 * the source of its file:
 *
 * ```ts
 * // .flags/self.ts
 * export { checkout, summerSale } from '../app.flags';
 * ```
 *
 * `flags/generated.d.ts` declares the modules `flags:<source>`, with the
 * type of each flag from its flags file. Nothing here uses the network.
 */
export async function writeFlagsFileSources(
  projectDirectory: string,
): Promise<FlagsFileSourcesResult> {
  const root = path.resolve(projectDirectory);
  const output = path.join(root, GENERATED_DIRECTORY);
  const flagsDirectory =
    (await findFlagsDirectory(root)) ?? (await defaultFlagsDirectory(root));
  const sources = new Map<string, SourceFlag[]>();
  const conflicts: string[] = [];
  for (const id of findFlagsFiles(root)) {
    const file = path.join(root, id);
    const document = parseFlagsFile(await readFile(file, 'utf8'));
    // A file without flags still defines its source, e.g. flags:self
    if (!sources.has(document.source)) {
      sources.set(document.source, []);
    }
    for (const flag of document.flags) {
      const flags = sources.get(flag.source) ?? [];
      sources.set(flag.source, flags);
      const other = flags.find(
        (existing) => existing.key === flag.key || existing.name === flag.name,
      );
      if (other) {
        const where = `${path.relative(root, other.file)} and in ${id}`;
        conflicts.push(
          other.key === flag.key
            ? `flags: The key "${flag.key}" of the source "${flag.source}" is declared in ${where}. Declare it in one file.`
            : `flags: The name ${flag.name} of the source "${flag.source}" is declared in ${where}, for the keys "${other.key}" and "${flag.key}". Rename one of them.`,
        );
        continue;
      }
      flags.push({
        key: flag.key,
        name: flag.name,
        file,
        doc: jsDocOf(flag, id),
      });
    }
  }

  const names = [...sources.keys()].sort();
  const declarations = [
    `${DECLARATIONS_HEADER} from the flags files. Do not edit.`,
    '',
  ];
  await mkdir(output, { recursive: true });
  // Git ignores the folder without a change to the .gitignore of the app
  await writeIfChanged(output, '.gitignore', '*\n');
  const aliases: FlagsAliases = {};
  for (const name of names) {
    assertSourceName(name);
    const flags = [...(sources.get(name) ?? [])].sort((a, b) =>
      a.name.localeCompare(b.name, 'en'),
    );
    const byFile = new Map<string, SourceFlag[]>();
    for (const flag of flags) {
      byFile.set(flag.file, [...(byFile.get(flag.file) ?? []), flag]);
    }
    const module = [
      `// Generated by the Flags SDK: the flags of the source "${name}" of all flags files. Do not edit.`,
      ...[...byFile]
        .sort(([a], [b]) => a.localeCompare(b, 'en'))
        .map(
          ([file, fileFlags]) =>
            `export { ${fileFlags.map((flag) => flag.name).join(', ')} } from ${JSON.stringify(importPath(output, file))};`,
        ),
      ...(flags.length === 0 ? ['export {};'] : []),
      '',
    ].join('\n');
    await writeIfChanged(output, `${name}.ts`, module);
    aliases[`flags:${name}`] = `./${GENERATED_DIRECTORY}/${name}.ts`;

    declarations.push(`declare module 'flags:${name}' {`);
    for (const [index, flag] of flags.entries()) {
      const local = `flag_${index}`;
      declarations.push(
        ...flag.doc.map((line) => `  ${line}`),
        `  const ${local}: (typeof import(${JSON.stringify(importPath(flagsDirectory, flag.file))}))[${JSON.stringify(flag.name)}];`,
        `  export { ${local} as ${flag.name} };`,
        '',
      );
    }
    if (flags.length === 0) {
      declarations.push('  export {};');
    }
    declarations.push('}', '');
  }
  // The module of a removed source must also go, e.g. from the editor
  for (const file of await readdir(output)) {
    if (file.endsWith('.ts') && !sources.has(file.slice(0, -3))) {
      await rm(path.join(output, file));
    }
  }
  await writeIfChanged(
    output,
    'aliases.json',
    `${JSON.stringify(aliases, null, 2)}\n`,
  );
  await mkdir(flagsDirectory, { recursive: true });
  await writeIfChanged(
    flagsDirectory,
    GENERATED_DECLARATIONS,
    declarations.join('\n'),
  );
  await removeOtherDeclarations(root, flagsDirectory);
  return { aliases, conflicts };
}

export interface WatchResult {
  /**
   * The aliases after the first write.
   */
  readonly aliases: FlagsAliases;
  /**
   * Resolves when the signal aborts.
   */
  readonly done: Promise<void>;
}

async function start(
  directory: string,
  watch: boolean,
  signal: AbortSignal | undefined,
): Promise<WatchResult> {
  const root = path.resolve(directory);
  signal?.throwIfAborted();
  // Without flags files there is nothing to write. A folder .flags of an
  // earlier run is cleaned up, so that no old module of a source stays.
  const hasGenerated = await stat(path.join(root, GENERATED_DIRECTORY))
    .then((info) => info.isDirectory())
    .catch(() => false);
  if (findFlagsFiles(root).length === 0 && !hasGenerated) {
    return { aliases: {}, done: Promise.resolve() };
  }
  // The types of each file, and the modules flags:<source>
  const write = async () => {
    const { problems } = await writeFlagsFileDeclarations(root);
    const { aliases, conflicts } = await writeFlagsFileSources(root);
    return { aliases, problems: [...problems, ...conflicts], conflicts };
  };
  const { aliases, problems, conflicts } = await write();
  if (!watch) {
    // A build must not have two declarations of one flag
    if (conflicts.length > 0) {
      throw new Error(conflicts.join('\n'));
    }
    for (const problem of problems) {
      console.error(problem);
    }
    return { aliases, done: Promise.resolve() };
  }
  for (const problem of problems) {
    console.error(problem);
  }
  const controller = new AbortController();
  const stop = () => controller.abort(signal?.reason);
  signal?.addEventListener('abort', stop, { once: true });
  watchFlagsFileDeclarations(root, controller.signal, undefined, write);
  const done = new Promise<void>((resolve) => {
    controller.signal.addEventListener('abort', () => resolve(), {
      once: true,
    });
  }).finally(() => {
    signal?.removeEventListener('abort', stop);
  });
  return { aliases, done };
}

/**
 * Writes the modules of `flags:<source>` and the types of the flags files
 * one time. Returns the aliases. A key or a name in two files of one source
 * fails.
 *
 * @param directory - The directory of the application.
 */
export async function generateFlags(
  directory: string = process.cwd(),
): Promise<FlagsAliases> {
  const { aliases } = await start(directory, false, undefined);
  return aliases;
}

/**
 * Writes the modules of `flags:<source>` and the types of the flags files,
 * and again after each change of a flags file, until the signal aborts.
 * Resolves when the first modules exist.
 *
 * @param directory - The directory of the application.
 */
export function watchFlags(
  directory: string,
  options: { readonly signal: AbortSignal },
): Promise<WatchResult> {
  return start(directory, true, options.signal);
}
