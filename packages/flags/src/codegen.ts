import type { Catalog } from './catalog';
import type { FlagType } from './value-types';

/**
 * Throws if the name of a source can not be a directory name and a part of
 * `flags:<source>`.
 *
 * @internal
 */
export function assertSourceName(name: string): void {
  if (!/^[a-z][a-z0-9_-]*$/i.test(name)) {
    throw new Error(`flags: Invalid name of a source: ${JSON.stringify(name)}`);
  }
}

function typeOfVariant(value: unknown): FlagType | undefined {
  if (typeof value === 'boolean') {
    return 'boolean';
  }
  if (typeof value === 'string') {
    return 'string';
  }
  if (typeof value === 'number') {
    return 'number';
  }
  if (typeof value === 'object' && value !== null && !Array.isArray(value)) {
    return 'object';
  }
  return undefined;
}

/**
 * The type of a flag from its variants. All variants must have one type,
 * because OpenFeature evaluates each flag with the method of one type.
 */
function typeOfFlag(key: string, variants: readonly unknown[]): FlagType {
  const types = new Set(variants.map(typeOfVariant));
  const [type] = types;
  if (types.size !== 1 || type === undefined) {
    throw new Error(
      `flags: The variants of flag ${JSON.stringify(key)} must all be booleans, strings, numbers or objects.`,
    );
  }
  return type;
}

function jsDoc(description: string): string[] {
  return [
    '/**',
    ...description
      .replace(/\*\//g, '*\\/')
      .split(/\r?\n/)
      .map((line) => ` * ${line}`),
    ' */',
  ];
}

/**
 * Writes the module of `flags:<source>` for a catalog. The module has the
 * `'use flags'` directive, one `defineSource` with the provider and the
 * context of `flags/sources/<source>`, and one `bindFlag` for each flag of
 * the catalog. The module is in `.flags`, so it imports the files of the
 * source with `../flags/sources/<source>/`.
 *
 * The same code can be written by hand.
 */
export function renderSourceModule(name: string, catalog: Catalog): string {
  assertSourceName(name);
  const project = catalog.project ?? { system: 'in-memory' };
  const lines = [
    '// Generated by flags sync / flags watch. Do not edit.',
    "'use flags';",
    '',
    "import { bindFlag, defineSource } from 'flags';",
    `import getEvaluationContext from '../flags/sources/${name}/context.ts';`,
    `import provider from '../flags/sources/${name}/provider.ts';`,
    '',
    'const source = defineSource({',
    '  provider,',
    `  project: ${JSON.stringify(project)},`,
    '  getEvaluationContext,',
    '});',
    '',
  ];

  const entries = Object.entries(catalog.flags).sort(([a], [b]) =>
    a.localeCompare(b, 'en'),
  );
  for (const [index, [key, flag]] of entries.entries()) {
    const type = typeOfFlag(key, flag.variants);
    // An option of an object flag must be { value }, because a JSON object
    // and an option object look the same
    const options =
      type === 'object'
        ? JSON.stringify(flag.variants.map((value) => ({ value })))
        : `${JSON.stringify(flag.variants)} as const`;
    // Private names, so that a key can have any characters, or be a
    // reserved word
    const local = `flag_${index}`;
    if (flag.description) {
      lines.push(...jsDoc(flag.description));
    }
    lines.push(
      `const ${local} = bindFlag({`,
      `  key: ${JSON.stringify(key)},`,
      '  source,',
      `  type: ${JSON.stringify(type)},`,
      `  options: ${options},`,
      ...(flag.description
        ? [`  description: ${JSON.stringify(flag.description)},`]
        : []),
      '});',
      `export { ${local} as ${JSON.stringify(key)} };`,
      '',
    );
  }
  return lines.join('\n');
}
