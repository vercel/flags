import type { Catalog, CatalogFlag } from './catalog';
import type { FlagType } from './value-types';

/**
 * Throws if the name of a source can not be a directory name and a part of
 * `flags:<source>`.
 *
 * @internal
 */
export function assertSourceName(name: string): void {
  if (!/^[a-z][a-z0-9_-]*$/i.test(name)) {
    throw new Error(`flags: Invalid name of a source: ${JSON.stringify(name)}`);
  }
}

/**
 * The type of a flag from its variants: `boolean`, `string` or `number` if
 * all variants have that type, else `object`. A flag of the type `object`
 * can have any JSON value, as with `resolveObjectEvaluation` of
 * OpenFeature, so it also takes variants of mixed types, e.g. objects and
 * `null`.
 *
 * @internal
 */
export function flagTypeOf(variants: readonly unknown[]): FlagType {
  if (variants.length > 0) {
    if (variants.every((value) => typeof value === 'boolean')) {
      return 'boolean';
    }
    if (variants.every((value) => typeof value === 'string')) {
      return 'string';
    }
    if (variants.every((value) => typeof value === 'number')) {
      return 'number';
    }
  }
  return 'object';
}

// A variant longer than this is shortened in the JSDoc, e.g. a large object
const MAX_VARIANT_LENGTH = 40;
const MAX_VARIANTS = 10;

/** A value as inline code of Markdown, also with a backtick in it. */
function inlineCode(value: unknown): string {
  let text = JSON.stringify(value) ?? String(value);
  if (text.length > MAX_VARIANT_LENGTH) {
    text = `${text.slice(0, MAX_VARIANT_LENGTH - 1)}…`;
  }
  return text.includes('`') ? `\`\` ${text} \`\`` : `\`${text}\``;
}

/**
 * The text of the JSDoc of a flag: what the catalog knows about it. The
 * description, if the catalog has one, then the variants and the default
 * value. The parts are paragraphs, so that the editor shows them on lines
 * of their own.
 */
function flagDoc(flag: CatalogFlag): string {
  const parts: string[] = [];
  if (flag.description) {
    parts.push(flag.description);
  }
  if (flag.variants.length > 0) {
    const shown = flag.variants.slice(0, MAX_VARIANTS).map(inlineCode);
    const more = flag.variants.length - shown.length;
    parts.push(
      `Variants: ${shown.join(', ')}${more > 0 ? `, and ${more} more` : ''}`,
    );
  }
  if (flag.defaultValue !== undefined) {
    parts.push(`Default value: ${inlineCode(flag.defaultValue)}`);
  }
  return parts.join('\n\n');
}

function jsDoc(description: string): string[] {
  return [
    '/**',
    ...description
      .replace(/\*\//g, '*\\/')
      .split(/\r?\n/)
      .map((line) => (line ? ` * ${line}` : ' *')),
    ' */',
  ];
}

/**
 * Which optional files a source has. `provider.ts` and `catalog.ts` are
 * required.
 */
export interface SourceFiles {
  /**
   * Whether the source has `context.ts`. The default is `true`.
   */
  readonly context?: boolean;
}

/**
 * Writes the module of `flags:<source>` for a catalog. The module has the
 * `'use flags'` directive, one `defineSource` with the provider and the
 * context of `flags/sources/<source>`, and one `bindFlag` for each flag of
 * the catalog. The module is in `.flags`, so it imports the files of the
 * source with `../flags/sources/<source>/`. The type of each flag comes
 * from its variants (see `flagTypeOf`).
 *
 * Without `context.ts` (`context: false`), the source has no evaluation
 * context of its own: only the context of the call side goes to the
 * provider.
 *
 * The same code can be written by hand.
 */
export function renderSourceModule(
  name: string,
  catalog: Catalog,
  sourcesPath = '../flags/sources',
  options: SourceFiles = {},
): string {
  assertSourceName(name);
  const context = options.context ?? true;
  const lines = [
    '// Generated by flags sync / flags watch. Do not edit.',
    "'use flags';",
    '',
    "import { bindFlag, defineSource } from 'flags';",
    ...(context
      ? [
          `import getEvaluationContext from '${sourcesPath}/${name}/context.ts';`,
        ]
      : []),
    `import provider from '${sourcesPath}/${name}/provider.ts';`,
    '',
    'const source = defineSource({',
    '  provider,',
    ...(catalog.project
      ? [`  project: ${JSON.stringify(catalog.project)},`]
      : []),
    ...(context ? ['  getEvaluationContext,'] : []),
    '});',
    '',
  ];

  const entries = Object.entries(catalog.flags).sort(([a], [b]) =>
    a.localeCompare(b, 'en'),
  );
  for (const [index, [key, flag]] of entries.entries()) {
    const type = flagTypeOf(flag.variants);
    // An option of an object flag must be { value }, because a JSON value
    // and an option object can look the same
    const options =
      type === 'object'
        ? JSON.stringify(flag.variants.map((value) => ({ value })))
        : `${JSON.stringify(flag.variants)} as const`;
    // Private names, so that a key can have any characters, or be a
    // reserved word
    const local = `flag_${index}`;
    const doc = flagDoc(flag);
    if (doc) {
      lines.push(...jsDoc(doc));
    }
    lines.push(
      `const ${local} = bindFlag({`,
      `  key: ${JSON.stringify(key)},`,
      '  source,',
      `  type: ${JSON.stringify(type)},`,
      `  options: ${options},`,
      ...(flag.description
        ? [`  description: ${JSON.stringify(flag.description)},`]
        : []),
      ...(flag.defaultValue !== undefined
        ? [`  defaultValue: ${JSON.stringify(flag.defaultValue)},`]
        : []),
      '});',
      `export { ${local} as ${JSON.stringify(key)} };`,
      '',
    );
  }
  return lines.join('\n');
}

/**
 * The TypeScript type of the value of a flag, from its variants, e.g.
 * `'control' | 'express' | (string & {})`. The provider can return a value
 * which is not a variant, so the type stays open.
 */
function valueTypeOf(variants: readonly unknown[]): string {
  const type = flagTypeOf(variants);
  if (type === 'boolean') {
    return 'boolean';
  }
  if (type === 'object') {
    return 'FlagObjectValue';
  }
  const known = [...new Set(variants.map((value) => JSON.stringify(value)))];
  return [...known, `(${type} & {})`].join(' | ');
}

/**
 * The name of the interface of a source, e.g. `SelfSource` for `self`.
 */
function sourceTypeName(name: string): string {
  const words = name.split(/[^a-z0-9]+/i).filter(Boolean);
  const pascal = words
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join('');
  return `${pascal}Source`;
}

/**
 * Writes the declarations of all modules `flags:<source>`, for the file
 * `generated.d.ts` in the folder `flags`. With them, TypeScript knows the
 * imports `flags:<source>` without `paths` in `tsconfig.json`: the folder is
 * part of the program of each usual configuration. The types come from the
 * files of each source, so the input of `context.ts` is checked.
 *
 * Each source has a named interface, e.g. `SelfSource`, so that the type of
 * a flag stays short in the editor: `Flag<SelfSource, 'key', …>`.
 */
export function renderDeclarations(
  catalogs: readonly (readonly [string, Catalog, SourceFiles?])[],
): string {
  const lines = [
    '// Generated by the Flags SDK from the catalogs of flags/sources. Do not edit.',
    '',
  ];
  for (const [name, catalog, files = {}] of catalogs) {
    assertSourceName(name);
    const source = sourceTypeName(name);
    // Without context.ts, the flags of the source take no input
    const input =
      (files.context ?? true)
        ? [
            `  type Context = (typeof import('./sources/${name}/context'))['default'];`,
            '  // The input after the request, or undefined without one',
            '  type Rest = Parameters<Context> extends [unknown, ...infer R] ? R : [];',
            '  type First = Rest extends [(infer I)?, ...unknown[]] ? I : undefined;',
            '  type Input = Rest extends [] ? undefined : First;',
          ]
        : ['  type Input = undefined;'];
    lines.push(
      `declare module 'flags:${name}' {`,
      '  import type {',
      '    EvaluationContext,',
      '    Flag,',
      '    FlagManagementSystem,',
      '    FlagObjectValue,',
      '    Source,',
      "  } from 'flags';",
      '',
      `  type Provider = (typeof import('./sources/${name}/provider'))['default'];`,
      ...input,
      '',
      `  /** The source \`${name}\` of \`flags/sources/${name}\`. */`,
      `  interface ${source}`,
      '    extends Source<Provider, FlagManagementSystem, EvaluationContext, Input> {}',
      '',
    );
    const entries = Object.entries(catalog.flags).sort(([a], [b]) =>
      a.localeCompare(b, 'en'),
    );
    for (const [index, [key, flag]] of entries.entries()) {
      const local = `flag_${index}`;
      const doc = flagDoc(flag);
      if (doc) {
        lines.push(...jsDoc(doc).map((line) => `  ${line}`));
      }
      lines.push(
        `  const ${local}: Flag<${source}, ${JSON.stringify(key)}, Input, ${valueTypeOf(flag.variants)}>;`,
        `  export { ${local} as ${JSON.stringify(key)} };`,
        '',
      );
    }
    lines.push('}', '');
  }
  return lines.join('\n');
}
