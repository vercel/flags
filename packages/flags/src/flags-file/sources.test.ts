import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import ts from 'typescript';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { generateFlags } from '../generate';

describe('flags:<source> for flags files', () => {
  let directory: string;

  beforeEach(async () => {
    directory = await mkdtemp(path.join(tmpdir(), 'flags-file-sources-'));
    await writeFile(path.join(directory, 'package.json'), '{}');
    for (const source of ['self', 'marketing']) {
      const folder = path.join(directory, 'flags/sources', source);
      await mkdir(folder, { recursive: true });
      await writeFile(
        path.join(folder, 'provider.ts'),
        `import { TypedInMemoryProvider } from '@openfeature/server-sdk';
export default new TypedInMemoryProvider({});`,
      );
    }
    await writeFile(
      path.join(directory, 'app.flags'),
      'flag summer-sale {\n  description: "The sale"\n  defaultValue: false\n}\n\nflag checkout {\n  options: ["control", "express"]\n}\n',
    );
    await mkdir(path.join(directory, 'checkout'));
    // A second file of the same source, next to its feature
    await writeFile(
      path.join(directory, 'checkout/checkout.flags'),
      'flag express-shipping\n',
    );
    await writeFile(
      path.join(directory, 'marketing.flags'),
      'source marketing\n\nflag hero-text {\n  defaultValue: "Welcome"\n}\n',
    );
  });

  afterEach(async () => {
    await rm(directory, { recursive: true, force: true });
  });

  it('writes one module for each source, with the flags of all its files', async () => {
    expect(await generateFlags(directory)).toEqual({
      'flags:marketing': './.flags/marketing.ts',
      'flags:self': './.flags/self.ts',
    });
    expect(
      await readFile(path.join(directory, '.flags/self.ts'), 'utf8'),
    ).toBe(`// Generated by the Flags SDK: the flags of the source "self" of all flags files. Do not edit.
export { checkout, summerSale } from "../app.flags";
export { expressShipping } from "../checkout/checkout.flags";
`);
    expect(
      JSON.parse(
        await readFile(path.join(directory, '.flags/aliases.json'), 'utf8'),
      ),
    ).toEqual({
      'flags:marketing': './.flags/marketing.ts',
      'flags:self': './.flags/self.ts',
    });
    const declarations = await readFile(
      path.join(directory, 'flags/generated.d.ts'),
      'utf8',
    );
    expect(declarations).toContain("declare module 'flags:self' {");
    expect(declarations).toContain(
      `  const flag_2: (typeof import("../app.flags"))["summerSale"];
  export { flag_2 as summerSale };`,
    );
  });

  it('gives each flag of flags:<source> the type of its file', async () => {
    await generateFlags(directory);
    const root = path.resolve(__dirname, '../..');
    const config = ts.readConfigFile(
      path.join(root, 'tsconfig.json'),
      ts.sys.readFile,
    );
    const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
    const options: ts.CompilerOptions = {
      ...parsed.options,
      noEmit: true,
      incremental: false,
      allowArbitraryExtensions: true,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      module: ts.ModuleKind.ESNext,
      baseUrl: root,
      paths: {
        ...parsed.options.paths,
        flags: [path.join(root, 'src/index.ts')],
        '@openfeature/server-sdk': [
          path.join(root, 'node_modules/@openfeature/server-sdk'),
        ],
      },
    };
    const consumer = path.join(directory, 'consumer.ts');
    await writeFile(
      consumer,
      `import { checkout, expressShipping, summerSale } from 'flags:self';
import { heroText } from 'flags:marketing';
import { summerSale as fromFile } from './app.flags';
const sale: Promise<boolean> = summerSale();
const flow: Promise<'control' | 'express' | (string & {})> = checkout();
const express: Promise<boolean> = expressShipping();
const hero: Promise<string> = heroText();
// The same flag, from its source and from its file
export const same: typeof fromFile = summerSale;
export { sale, flow, express, hero };
`,
    );
    const program = ts.createProgram(
      [consumer, path.join(directory, 'flags/generated.d.ts')],
      options,
    );
    expect(
      ts
        .getPreEmitDiagnostics(program)
        .map((diagnostic) =>
          ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'),
        ),
    ).toEqual([]);
  });

  it('fails a build if two files of one source declare the same flag', async () => {
    await writeFile(
      path.join(directory, 'checkout/checkout.flags'),
      'flag checkout\n',
    );
    await expect(generateFlags(directory)).rejects.toThrow(
      'flags: The flag "checkout" of the source "self" is declared in app.flags and in checkout/checkout.flags. Declare it in one file.',
    );
  });
});
