import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { runCommand } from './commands';
import { generateFlags, watchFlags } from './generate';

const cleanups: (() => Promise<void>)[] = [];

afterEach(async () => {
  for (const cleanup of cleanups.splice(0).reverse()) {
    await cleanup();
  }
});

async function app(): Promise<string> {
  const directory = await mkdtemp(path.join(tmpdir(), 'flags-generate-'));
  cleanups.push(() =>
    rm(directory, { recursive: true, force: true, maxRetries: 5 }),
  );
  await writeFile(path.join(directory, 'package.json'), '{}');
  return directory;
}

const exists = (file: string) =>
  readFile(file, 'utf8').then(
    () => true,
    () => false,
  );

const read = (directory: string, file: string) =>
  readFile(path.join(directory, file), 'utf8');

async function waitFor(check: () => Promise<boolean>): Promise<void> {
  for (let attempt = 0; attempt < 100; attempt++) {
    if (await check()) {
      return;
    }
    await new Promise((resolve) => setTimeout(resolve, 50));
  }
  throw new Error('The condition did not become true.');
}

describe('generateFlags', () => {
  it('writes nothing for an application without flags files', async () => {
    const directory = await app();

    expect(await generateFlags(directory)).toEqual({});
    expect(await exists(path.join(directory, '.flags/aliases.json'))).toBe(
      false,
    );
    expect(await exists(path.join(directory, 'flags/generated.d.ts'))).toBe(
      false,
    );
  });

  it('defines the source of a flags file without flags', async () => {
    const directory = await app();
    // A file without `source` has the source self
    await writeFile(path.join(directory, 'app.flags'), '// No flags yet\n');

    expect(await generateFlags(directory)).toEqual({
      'flags:self': './.flags/self.ts',
    });
    expect(await read(directory, '.flags/self.ts')).toBe(
      `// Generated by the Flags SDK: the flags of the source "self" of all flags files. Do not edit.
export {};
`,
    );
    expect(await read(directory, 'flags/generated.d.ts')).toContain(
      "declare module 'flags:self' {\n  export {};\n}",
    );
  });

  it('defines no flags:self without a flags file of the source self', async () => {
    const directory = await app();
    await writeFile(
      path.join(directory, 'marketing.flags'),
      'source marketing\n\nflag heroText\n',
    );

    expect(await generateFlags(directory)).toEqual({
      'flags:marketing': './.flags/marketing.ts',
    });
    expect(await read(directory, 'flags/generated.d.ts')).not.toContain(
      "'flags:self'",
    );
  });

  it('removes the module of a source which no flags file has any more', async () => {
    const directory = await app();
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');
    await writeFile(
      path.join(directory, 'marketing.flags'),
      'source marketing\n\nflag heroText\n',
    );
    await generateFlags(directory);

    await rm(path.join(directory, 'marketing.flags'));
    expect(await generateFlags(directory)).toEqual({
      'flags:self': './.flags/self.ts',
    });
    expect(await exists(path.join(directory, '.flags/marketing.ts'))).toBe(
      false,
    );
  });

  it('cleans up the modules of an earlier run when no flags file is left', async () => {
    const directory = await app();
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');
    await generateFlags(directory);

    await rm(path.join(directory, 'app.flags'));
    expect(await generateFlags(directory)).toEqual({});
    expect(await exists(path.join(directory, '.flags/self.ts'))).toBe(false);
    expect(JSON.parse(await read(directory, '.flags/aliases.json'))).toEqual(
      {},
    );
  });

  it('writes the types into src/flags if the application has src', async () => {
    const directory = await app();
    await mkdir(path.join(directory, 'src'));
    await writeFile(path.join(directory, 'src/app.flags'), 'flag summerSale\n');

    await generateFlags(directory);
    expect(await exists(path.join(directory, 'src/flags/generated.d.ts'))).toBe(
      true,
    );
    expect(await exists(path.join(directory, 'flags/generated.d.ts'))).toBe(
      false,
    );
  });

  it('writes the types next to an existing folder flags', async () => {
    const directory = await app();
    await mkdir(path.join(directory, 'src'));
    // e.g. with flags/hooks.ts in the root
    await mkdir(path.join(directory, 'flags'));
    await writeFile(
      path.join(directory, 'flags/hooks.ts'),
      'export default [];',
    );
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');

    await generateFlags(directory);
    expect(await exists(path.join(directory, 'flags/generated.d.ts'))).toBe(
      true,
    );
  });

  it('removes its old types when the folder flags moves, and keeps other files', async () => {
    const directory = await app();
    await mkdir(path.join(directory, 'src'));
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');
    await generateFlags(directory);
    expect(await exists(path.join(directory, 'src/flags/generated.d.ts'))).toBe(
      true,
    );

    // The application creates a folder flags in the root
    await mkdir(path.join(directory, 'flags/sources/self'), {
      recursive: true,
    });
    await generateFlags(directory);
    expect(await exists(path.join(directory, 'flags/generated.d.ts'))).toBe(
      true,
    );
    expect(await exists(path.join(directory, 'src/flags/generated.d.ts'))).toBe(
      false,
    );

    // A generated.d.ts which the SDK did not write stays
    await writeFile(
      path.join(directory, 'src/flags/generated.d.ts'),
      'declare const own: string;\n',
    );
    await generateFlags(directory);
    expect(await read(directory, 'src/flags/generated.d.ts')).toBe(
      'declare const own: string;\n',
    );
  });
});

describe('watchFlags', () => {
  it('writes the modules again after each change of a flags file', async () => {
    const directory = await app();
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');
    const controller = new AbortController();

    const { aliases, done } = await watchFlags(directory, {
      signal: controller.signal,
    });
    expect(aliases).toEqual({ 'flags:self': './.flags/self.ts' });

    await writeFile(
      path.join(directory, 'app.flags'),
      'flag summerSale\n\nflag checkout\n',
    );
    await waitFor(async () =>
      (await read(directory, '.flags/self.ts')).includes('checkout'),
    );

    controller.abort();
    await done;
  });
});

describe('flags sync', () => {
  it('writes the modules and the types of the flags files', async () => {
    const directory = await app();
    await writeFile(path.join(directory, 'app.flags'), 'flag summerSale\n');

    expect(await runCommand(['sync', directory])).toBe(
      'flags: Wrote the types of 1 flags file. The sources are flags:self.',
    );
    expect(await exists(path.join(directory, '.flags/self.ts'))).toBe(true);
  });

  it('says when there is no flags file', async () => {
    const directory = await app();

    expect(await runCommand(['sync', directory])).toBe(
      'flags: No flags files (*.flags) in the directory.',
    );
  });

  it('has no option --production any more', async () => {
    const directory = await app();

    await expect(
      runCommand(['sync', directory, '--production']),
    ).rejects.toThrow('Usage: flags manifest');
  });
});
